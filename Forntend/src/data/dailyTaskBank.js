// Default fallback subject generator to ensure ANY task gets 20 questions strictly matching student's group
export const getTaskChallengeContent = (task, userGroup = '') => {
  if (!task) return null;
  const group = (userGroup || task.group || 'Science').trim();
  const subjectKey = (task.subject || '').trim();

  let pool = null;
  const subLower = subjectKey.toLowerCase();
  const grpLower = group.toLowerCase();

  // Subject matching:
  if (subLower.includes('acc') || subLower.includes('হিসাব')) {
    pool = TASK_CHALLENGE_BANK['Accounting'];
  } else if (subLower.includes('bus') || subLower.includes('ব্যবসা') || subLower.includes('ব্যবস্থাপনা')) {
    pool = TASK_CHALLENGE_BANK['Business'];
  } else if (subLower.includes('fin') || subLower.includes('অর্থ') || subLower.includes('ict')) {
    pool = TASK_CHALLENGE_BANK['Finance'];
  } else if (subLower.includes('bangla') || subLower.includes('বাংলা') || subLower.includes('সাহিত্য')) {
    pool = TASK_CHALLENGE_BANK['Bangla'];
  } else if (subLower.includes('gk') || subLower.includes('জ্ঞান') || subLower.includes('general')) {
    pool = TASK_CHALLENGE_BANK['GK'];
  } else if (subLower.includes('chem') || subLower.includes('রসায়ন')) {
    pool = TASK_CHALLENGE_BANK['Chemistry'];
  } else if (subLower.includes('math') || subLower.includes('গণিত')) {
    pool = TASK_CHALLENGE_BANK['Math'];
  } else if (subLower.includes('bio') || subLower.includes('জীব')) {
    pool = TASK_CHALLENGE_BANK['Biology'];
  } else if (subLower.includes('eng') || subLower.includes('ইংরেজি')) {
    pool = TASK_CHALLENGE_BANK['English'];
  } else if (subLower.includes('phy') || subLower.includes('পদার্থ')) {
    pool = TASK_CHALLENGE_BANK['Physics'];
  } else if (subLower.includes('mock') || subLower.includes('মক') || subLower.includes('টেস্ট') || subLower.includes('কুইজ')) {
    // For Mock Test task, assemble a 20-question challenge strictly for the student's group!
    if (grpLower === 'commerce') {
      pool = [
        ...TASK_CHALLENGE_BANK['Accounting'].slice(0, 8),
        ...TASK_CHALLENGE_BANK['Business'].slice(0, 6),
        ...TASK_CHALLENGE_BANK['Finance'].slice(0, 6)
      ];
    } else if (grpLower === 'arts' || grpLower === 'humanities') {
      pool = [
        ...TASK_CHALLENGE_BANK['Bangla'].slice(0, 8),
        ...TASK_CHALLENGE_BANK['English'].slice(0, 6),
        ...TASK_CHALLENGE_BANK['GK'].slice(0, 6)
      ];
    } else {
      pool = [
        ...TASK_CHALLENGE_BANK['Physics'].slice(0, 5),
        ...TASK_CHALLENGE_BANK['Chemistry'].slice(0, 5),
        ...TASK_CHALLENGE_BANK['Math'].slice(0, 5),
        ...TASK_CHALLENGE_BANK['Biology'].slice(0, 5)
      ];
    }
  }

  // Fallback strictly tailored by group (NEVER give Physics to Commerce/Arts)
  if (!pool || pool.length === 0) {
    if (grpLower === 'commerce') pool = TASK_CHALLENGE_BANK['Accounting'];
    else if (grpLower === 'arts' || grpLower === 'humanities') pool = TASK_CHALLENGE_BANK['Bangla'];
    else pool = TASK_CHALLENGE_BANK['Physics'];
  }

  // Ensure exactly 20 questions
  let final20 = [...pool];
  if (final20.length < 20) {
    let extra = [];
    if (grpLower === 'commerce') {
      extra = [...TASK_CHALLENGE_BANK['Business'], ...TASK_CHALLENGE_BANK['Finance']];
    } else if (grpLower === 'arts' || grpLower === 'humanities') {
      extra = [...TASK_CHALLENGE_BANK['GK'], ...TASK_CHALLENGE_BANK['English']];
    } else {
      extra = [...TASK_CHALLENGE_BANK['Chemistry'], ...TASK_CHALLENGE_BANK['Math']];
    }
    while (final20.length < 20 && extra.length > 0) {
      final20.push(extra.shift());
    }
  }
  final20 = final20.slice(0, 20);

  // Group-aware formulas & revision guidelines
  let formulas = [
    'প্রতিটি সঠিক উত্তরের জন্য: +১ কয়েন',
    'প্রতিটি ভুল উত্তরের জন্য: -১ কয়েন পেনাল্টি কাটা যাবে',
    'মোট প্রশ্ন: ২০টি (সর্বোচ্চ অর্জন: ২০ কয়েন)'
  ];

  if (grpLower === 'commerce') {
    formulas.push('হিসাব সমীকরণ: সম্পদ = দায় + মালিকানাস্বত্ব (A = L + OE)');
    formulas.push('চলতি অনুপাত (Current Ratio) = চলতি সম্পদ / চলতি দায় (আদর্শ মান ২:১)');
  } else if (grpLower === 'arts' || grpLower === 'humanities') {
    formulas.push('বাংলা ব্যাকরণ: সন্ধি ধ্বনিভিত্তিক এবং সমাস অর্থভিত্তিক মিলন');
    formulas.push('সংবিধানের মূলনীতি ৪টি: জাতীয়তাবাদ, সমাজতন্ত্র, গণতন্ত্র ও ধর্মনিরপেক্ষতা');
  } else {
    formulas.push('পদার্থ ও গতিসূত্র: v = u + at, s = ut + ½at²');
    formulas.push('রসায়ন মোল সংখ্যা: n = W/M = V/22.4');
  }

  return {
    taskId: task.id,
    taskTitle: task.task,
    subject: task.subject,
    group: group,
    time: task.time || '১ ঘণ্টা',
    coins: 20, // Exactly 20 coins potential
    totalQuestions: 20,
    penaltyPerWrong: 1, // 1 point deduction per wrong answer
    topic: `${task.subject} (${group} গ্রুপ অনুশীলন)`,
    formulas: formulas,
    questions: final20
  };
};
